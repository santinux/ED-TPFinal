public class Puerta
{
        private int habitacionEntrada;
        private int habitacionSalida;
        private int puntajeRequerido;
        
        public Puerta(int unaHabitacionEntrada, int unaHabitacionSalida, int unPuntajeRequerido)
        {
                this.habitacionEntrada = unaHabitacionEntrada;
                this.habitacionSalida = unaHabitacionSalida;
                this.puntajeRequerido = unPuntajeRequerido;
        }
}
